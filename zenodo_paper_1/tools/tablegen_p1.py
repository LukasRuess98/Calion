def tab_synth_anova():
    s = pd.read_csv(f"{A}/synth_factorial_decomposition.csv")
    import re as _re
    def parse(n):
        m = _re.match(r"synth_n(\d+)_L([\dp]+?)km_hi([\dp]+)_s(\d+)h", n)
        return (int(m.group(1)), float(m.group(2).replace("p", ".")),
                float(m.group(3).replace("p", ".")), int(m.group(4))) if m else (0, 0, 0, 0)
    s[["n", "L", "hi", "s"]] = pd.DataFrame(s["net"].map(parse).tolist(), index=s.index)
