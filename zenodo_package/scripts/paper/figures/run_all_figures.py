def main() -> None:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    results: list[dict[str, object]] = []

    for spec in FIGURE_SCRIPTS:
        mod_name = str(spec["module"])
        stem = str(spec["stem"])
        started_at = time.time()
        message = ""
        try:
            mod = importlib.import_module(mod_name)
            mod.main()
            outputs = _fresh_outputs(stem, started_at)
            status = "exported" if outputs else "skipped"
            if not outputs:
                missing = _missing_required_paths(spec)
                if missing:
                    message = "Missing required input file(s): " + ", ".join(missing)
                else:
                    message = "No fresh output files were written; input data may be unavailable."
            print(f"[{status.upper()}] {mod_name.split('.')[-1]}")
        except Exception as exc:
            outputs = []
            status = "failed"
            message = str(exc)
            print(f"[ERR] {mod_name.split('.')[-1]}: {exc}")

        results.append({
            "module": mod_name,
            "stem": stem,
            "inputs": spec["inputs"],
            "status": status,
            "outputs": [str(path) for path in outputs],
            "message": message,
        })

    _write_report(results)
    print(f"[REPORT] {FIG_DIR / 'figure_polish_report.md'}")


if __name__ == "__main__":
    main()
