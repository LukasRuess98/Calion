        "scripts/paper/figures/fig_synth_gap_decomp.py",
        "scripts/paper/figures/fig_demand_per_node.py",
        "scripts/paper/figures/fig_cost_extended.py",
        "scripts/paper/figures/fig_cost_topology.py",
        "scripts/paper/figures/fig_cost_waterfall.py",
        "scripts/paper/figures/fig_dispatch_heatmap.py",
