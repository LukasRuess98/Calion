"""AD3 (2026-10-22): rebuild tab_T_TES_value_summary.tex with BOTH value definitions.

  package value      = TAC(PIN0) - TAC(free)                  (HP + EK + TES invested together)
  storage-only value = TAC(TES-free, HP/EK free) - TAC(free)  (the storage alone)

Reads docs/paper_2/submission_pack/02_tables/tab_Z5b_package_vs_storage_only.csv (written by
z5_rebuild_table.py), so the .tex can be regenerated whenever new runs finish. Rows whose run does not
exist yet are skipped.   usage: python scripts/paper_2/gen_tab_tes_value_summary.py
"""
import csv
from pathlib import Path

R = Path(__file__).resolve().parents[2]
CSV = R / "docs/paper_2/submission_pack/02_tables/tab_Z5b_package_vs_storage_only.csv"
OUT = R / "docs/paper_2/submission_pack/02_tables/tab_T_TES_value_summary.tex"
rows = {(r["network"], r["case"]): r for r in csv.DictReader(open(CSV, encoding="utf-8"))}


def num(x):
    return "--" if x in (None, "", "None") else f"{int(round(float(x))):,}".replace(",", "{,}")


def storage_cells(r):
    if r["storage_only_lo_eur_a"] in ("", None):
        return r"\multicolumn{2}{c}{n/a$^{c}$}"
    return f"{num(r['storage_only_lo_eur_a'])} & {num(r['storage_only_hi_eur_a'])}"


# (section title, [(network, case key in the CSV, printed label, footnote marker)])
SECTIONS = [
    (r"Old model: charge/discharge power free (E/P bound 4\,h, H/D 2, no height cap)", [
        ("SB", "base c0x1.0", r"x1.0 (179\,EUR/m$^3$)", ""),
        ("SB", "c0x1.3", "x1.3 (233)", "a"),
        ("SB", "c0x1.5", "x1.5 (269)", "a"),
        ("SB", "c0x2.0", "x2.0 (752)", ""),
        ("SB", "price amplitude x1.5", r"Price amplitude $\times$1.5", ""),
        ("SB", "price amplitude x2.0", r"Price amplitude $\times$2.0", ""),
        ("SB", "grid fee -50%", r"Grid fee $-$50\%", ""),
        ("SB", "monthly billing", "Monthly peak billing", ""),
        ("SB", "marketing -2 EUR/MWh", r"Marketing discount $-2$\,EUR/MWh", ""),
        ("MM", "base", "Memmingen, base case", ""),
    ]),
    (r"Power priced (range from DEA heating-installation substations, see text)", [
        ("SB", "AD1 low: power 8,800 EUR/MW, c0x1.0, H/D 1.5, h<=45 m", r"Low 8.8\,kEUR/MW", ""),
        ("SB", "AD1 mid: power 22,100 EUR/MW, c0x1.0, H/D 1.5, h<=45 m", r"Mid 22.1\,kEUR/MW", ""),
        ("SB", "AC1 high: power 75,185 EUR/MW, c0x1.0", r"High 75--76\,kEUR/MW", ""),
        ("SB", "AC1 stress: power 280,274 EUR/MW (scope-mismatched, withdrawn as base)",
         r"Stress 280\,kEUR/MW", "d"),
        ("SB", "AD1 mid, c0x1.5", "Mid, tank cost x1.5", ""),
        ("SB", "AD2 mid, E/P >= 8 h", r"Mid, E/P $\ge$ 8\,h", ""),
        ("SB", "AD2 mid, E/P >= 12 h", r"Mid, E/P $\ge$ 12\,h", ""),
        ("SB", "AD5 mid, H/D 2.0 (geometry sensitivity)", "Mid, H/D 2.0 (two vessels)", ""),
        ("SB", "AD4 mid, price amplitude x1.5", r"Mid, price amplitude $\times$1.5", ""),
        ("SB", "AD4 mid, price amplitude x2.0", r"Mid, price amplitude $\times$2.0", ""),
    ]),
]

body = []
n_rows = 0
for title, items in SECTIONS:
    lines = []
    for net, key, label, fn in items:
        r = rows.get((net, key))
        if r is None:
            continue
        sup = "$^{" + fn + "}$" if fn else ""
        lines.append(f"{label}{sup} & {num(r['package_value_lo_eur_a'])} & {num(r['package_value_hi_eur_a'])}"
                     f" & {storage_cells(r)} \\\\")
    if lines:
        n_rows += len(lines)
        body.append(r"\multicolumn{5}{@{}l}{\textit{" + title + r"}} \\")
        body += lines
        body.append(r"\addlinespace")
if body and body[-1] == r"\addlinespace":
    body.pop()

HEAD = r"""% =============================================================================
% tab_T_TES_value_summary.tex -- GENERATED by scripts/paper_2/gen_tab_tes_value_summary.py
% from tab_Z5b_package_vs_storage_only.csv (AD3, 2026-10-22). Do not edit by hand.
% =============================================================================
\begin{table}[t]
\centering
\caption{Investment value in the Stadtbach network (storage co-located with the primary producer),
two definitions. \emph{Package value} $=\mathrm{TAC}(\mathrm{PIN0})-\mathrm{TAC}(\mathrm{free})$:
heat pump, electrode boiler and storage invested together; PIN0 allows no investment.
\emph{Storage-only value} $=\mathrm{TAC}(\mathrm{storage\mbox{-}free})-\mathrm{TAC}(\mathrm{free})$:
the same model with heat pump and electrode boiler free but the storage switched off.
Intervals use each run's own MIP gap (never negative). The earlier 165--230\,kEUR/yr are
\emph{package} values; the storage alone is worth less, and with charge/discharge power priced
it is worth little or nothing. $^{a}$\,Gurobi log shows a single incumbent and an unchanged built size:
upper bound, not a re-optimised value. $^{c}$\,Storage-free reference for this tariff case not run.
$^{d}$\,Withdrawn as a base value: the DEA position is a transmission-network interface station
including civil works, not a tank connection; shown only as a stress test.}
\label{tab:tes_value_summary}
\small
\setlength{\tabcolsep}{4pt}
\begin{tabular}{@{}l r r r r@{}}
\toprule
Scenario & \multicolumn{2}{c}{Package value (EUR/yr)} & \multicolumn{2}{c}{Storage-only value (EUR/yr)} \\
 & min & max & min & max \\
\midrule
"""
TAIL = r"""
\bottomrule
\end{tabular}
\end{table}
"""
OUT.write_text(HEAD + "\n".join(body) + TAIL, encoding="utf-8")
print("wrote", OUT.name, "data rows:", n_rows)
